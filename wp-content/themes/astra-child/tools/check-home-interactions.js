(async () => {
    const results = {};
    const assert = (name, condition) => { results[name] = Boolean(condition); if (!condition) throw new Error(name); };
    const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
    const notice = document.querySelector('[data-notice]');
    assert('opening notice opens automatically', notice.open);
    notice.querySelector('[data-notice-close]').click();
    assert('opening notice closes', !notice.open);
    const dots = [...document.querySelectorAll('[data-slide]')];
    dots[2].click();
    assert('banner indicator selects image', !document.querySelectorAll('.micada-slide')[2].hidden && dots[2].getAttribute('aria-pressed') === 'true');
    await wait(3200);
    assert('banner advances automatically', dots[3].getAttribute('aria-pressed') === 'true');
    document.querySelector('[data-photo="0"]').click();
    const lightbox = document.querySelector('[data-lightbox]');
    assert('photo preview opens', lightbox.open);
    const first = lightbox.querySelector('img').src;
    lightbox.querySelector('[data-photo-next]').click();
    assert('photo next changes image', lightbox.querySelector('img').src !== first);
    lightbox.querySelector('[data-photo-previous]').click();
    assert('photo previous restores image', lightbox.querySelector('img').src === first);
    lightbox.querySelector('[data-lightbox-close]').click();
    assert('photo preview closes', !lightbox.open);
    const dropdown = document.querySelector('.micada-menu details');
    dropdown.querySelector('summary').click();
    assert('menu dropdown opens', dropdown.open);
    document.body.click();
    assert('menu dropdown closes outside', !dropdown.open);
    assert('five local application destinations', [...document.querySelectorAll('.login-button-section a')].filter(link => link.origin === location.origin && new URL(link.href).searchParams.get('micada_app')?.startsWith('phone-login/')).length === 5);
    assert('13 gallery photos retained', document.querySelectorAll('[data-photo]').length === 13);
    assert('ten homepage video embeds retained', document.querySelectorAll('.video-iframe-wrapper iframe').length === 10);
    assert('no horizontal overflow', document.documentElement.scrollWidth <= innerWidth);
    if (innerWidth <= 960) {
        const button = document.querySelector('.micada-menu-toggle');
        button.click();
        assert('mobile menu opens', button.getAttribute('aria-expanded') === 'true');
        button.click();
        assert('mobile menu closes', button.getAttribute('aria-expanded') === 'false');
    }
    const rti = document.querySelector('.micada-menu a[href*="section=rti"]');
    rti.click();
    for (let i = 0; i < 50 && !document.querySelector('.micada-cms-panel'); i++) await wait(100);
    assert('RTI loads in homepage content panel', Boolean(document.querySelector('.micada-cms-panel table')));
    assert('RTI updates browser history', new URL(location.href).searchParams.get('section') === 'rti');
    document.querySelector('.micada-menu a[href$="#micada-panels"]:not([href*="section="])').click();
    for (let i = 0; i < 50 && document.querySelector('.micada-cms-panel'); i++) await wait(100);
    assert('About Us restores homepage content', Boolean(document.querySelector('.micada-about')));
    return results;
})();
